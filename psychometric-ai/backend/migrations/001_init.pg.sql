-- 001_init.pg.sql — Psychometric AI schema v2 (PostgreSQL)
-- Faithful translation of 001_init.sql (SQLite). Value semantics are kept
-- IDENTICAL between engines:
--   * timestamps are TEXT in UTC 'YYYY-MM-DD HH:MM:SS' (lexicographic-safe)
--   * booleans remain INTEGER 0/1 so `is_active = 1` works unchanged
--   * REAL → DOUBLE PRECISION (both are IEEE-754 8-byte floats)
-- The pg driver additionally rewrites runtime datetime('now') calls.

-- =========================================================
-- 1. IDENTITY & PROFILES
-- =========================================================
CREATE TABLE IF NOT EXISTS users (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    email TEXT UNIQUE,
    phone TEXT UNIQUE,
    role TEXT NOT NULL CHECK (role IN ('candidate', 'parent', 'admin')),
    password_hash TEXT NOT NULL,
    is_active INTEGER NOT NULL DEFAULT 1,
    is_demo INTEGER NOT NULL DEFAULT 0,
    otp_code_hash TEXT,
    otp_expires_at TEXT,
    otp_attempts INTEGER NOT NULL DEFAULT 0,
    otp_locked_until TEXT,
    last_login_at TEXT,
    created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    updated_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE IF NOT EXISTS students (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    user_id INTEGER NOT NULL UNIQUE,
    full_name TEXT NOT NULL,
    dob TEXT,
    grade INTEGER NOT NULL DEFAULT 10 CHECK (grade BETWEEN 1 AND 12),
    school_name TEXT,
    board TEXT NOT NULL DEFAULT 'CBSE',
    student_code TEXT NOT NULL UNIQUE,
    profile_completed INTEGER NOT NULL DEFAULT 0,
    is_demo INTEGER NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    updated_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS parents (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    user_id INTEGER NOT NULL UNIQUE,
    full_name TEXT NOT NULL,
    phone TEXT,
    relationship TEXT NOT NULL DEFAULT 'Parent',
    occupation TEXT,
    is_demo INTEGER NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    updated_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

-- Linkage WITH consent lifecycle: a parent request stays 'pending_student_approval'
-- until the student (or guardian email verification in a future iteration) approves.
CREATE TABLE IF NOT EXISTS student_parent_mapping (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    student_id INTEGER NOT NULL,
    parent_id INTEGER NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending_student_approval'
        CHECK (status IN ('pending_student_approval', 'linked', 'revoked')),
    requested_by TEXT NOT NULL DEFAULT 'parent' CHECK (requested_by IN ('parent', 'student', 'admin')),
    student_consented_at TEXT,
    linked_at TEXT,
    created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    updated_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    FOREIGN KEY (student_id) REFERENCES students(id) ON DELETE CASCADE,
    FOREIGN KEY (parent_id) REFERENCES parents(id) ON DELETE CASCADE,
    UNIQUE(student_id, parent_id)
);

-- =========================================================
-- 2. ASSESSMENT STRUCTURE (VERSIONED)
-- =========================================================
CREATE TABLE IF NOT EXISTS assessment_versions (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    version_code TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    description TEXT,
    is_active INTEGER NOT NULL DEFAULT 1,
    created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE IF NOT EXISTS assessments (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    student_id INTEGER NOT NULL,
    version_id INTEGER NOT NULL,
    status TEXT NOT NULL DEFAULT 'in_progress' CHECK (status IN ('in_progress', 'completed', 'archived')),
    current_step INTEGER NOT NULL DEFAULT 1,
    started_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    completed_at TEXT,
    created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    updated_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    FOREIGN KEY (student_id) REFERENCES students(id) ON DELETE CASCADE,
    FOREIGN KEY (version_id) REFERENCES assessment_versions(id)
);

CREATE TABLE IF NOT EXISTS questions (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    version_id INTEGER NOT NULL,
    module TEXT NOT NULL CHECK (module IN ('aptitude', 'riasec', 'grit', 'parent_perception', 'parent_expectation')),
    category TEXT NOT NULL,
    difficulty TEXT CHECK (difficulty IN ('easy', 'medium', 'hard')),
    question_text TEXT NOT NULL,
    question_type TEXT NOT NULL CHECK (question_type IN ('single_choice', 'likert_5', 'categorical')),
    dimension TEXT NOT NULL,
    scoring_rule_json TEXT,
    display_order INTEGER NOT NULL DEFAULT 0,
    is_active INTEGER NOT NULL DEFAULT 1,
    difficulty_b DOUBLE PRECISION DEFAULT 0.0,
    discrimination_a DOUBLE PRECISION DEFAULT 1.0,
    guessing_c DOUBLE PRECISION DEFAULT 0.25,
    created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    updated_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    FOREIGN KEY (version_id) REFERENCES assessment_versions(id)
);

CREATE TABLE IF NOT EXISTS question_options (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    question_id INTEGER NOT NULL,
    option_key TEXT NOT NULL,
    option_text TEXT NOT NULL,
    score_value DOUBLE PRECISION NOT NULL DEFAULT 0,
    dimension_target TEXT,
    display_order INTEGER NOT NULL DEFAULT 0,
    FOREIGN KEY (question_id) REFERENCES questions(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS responses (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    assessment_id INTEGER NOT NULL,
    question_id INTEGER NOT NULL,
    respondent_type TEXT NOT NULL DEFAULT 'student' CHECK (respondent_type IN ('student', 'parent')),
    parent_id INTEGER,
    selected_option_id INTEGER,
    numeric_value DOUBLE PRECISION,
    response_time_ms INTEGER DEFAULT 0,
    created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    updated_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    FOREIGN KEY (assessment_id) REFERENCES assessments(id) ON DELETE CASCADE,
    FOREIGN KEY (question_id) REFERENCES questions(id),
    FOREIGN KEY (selected_option_id) REFERENCES question_options(id),
    FOREIGN KEY (parent_id) REFERENCES parents(id)
);

-- One stored answer per (assessment, question, respondent); COALESCE folds NULL parent_id
-- so the student slot is also deduplicated (expression index — COALESCE is IMMUTABLE in PG).
CREATE UNIQUE INDEX IF NOT EXISTS uq_responses_respondent
    ON responses(assessment_id, question_id, respondent_type, COALESCE(parent_id, 0));

-- =========================================================
-- 3. DETERMINISTIC SCORES
-- =========================================================
-- Naming: *_idx = normalized index on a 0-100 scale. NOT a percentile —
-- no normative population exists for this instrument (see docs/PSYCHOMETRIC_LIMITATIONS.md).
CREATE TABLE IF NOT EXISTS aptitude_scores (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    assessment_id INTEGER NOT NULL UNIQUE,
    numerical_raw DOUBLE PRECISION NOT NULL DEFAULT 0,
    numerical_idx DOUBLE PRECISION NOT NULL DEFAULT 0,
    abstract_raw DOUBLE PRECISION NOT NULL DEFAULT 0,
    abstract_idx DOUBLE PRECISION NOT NULL DEFAULT 0,
    verbal_raw DOUBLE PRECISION NOT NULL DEFAULT 0,
    verbal_idx DOUBLE PRECISION NOT NULL DEFAULT 0,
    spatial_raw DOUBLE PRECISION NOT NULL DEFAULT 0,
    spatial_idx DOUBLE PRECISION NOT NULL DEFAULT 0,
    logical_raw DOUBLE PRECISION NOT NULL DEFAULT 0,
    logical_idx DOUBLE PRECISION NOT NULL DEFAULT 0,
    data_raw DOUBLE PRECISION NOT NULL DEFAULT 0,
    data_idx DOUBLE PRECISION NOT NULL DEFAULT 0,
    overall_idx DOUBLE PRECISION NOT NULL DEFAULT 0,
    items_answered INTEGER NOT NULL DEFAULT 0,
    items_expected INTEGER NOT NULL DEFAULT 0,
    complete INTEGER NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    FOREIGN KEY (assessment_id) REFERENCES assessments(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS riasec_scores (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    assessment_id INTEGER NOT NULL UNIQUE,
    r_score DOUBLE PRECISION NOT NULL DEFAULT 0,
    i_score DOUBLE PRECISION NOT NULL DEFAULT 0,
    a_score DOUBLE PRECISION NOT NULL DEFAULT 0,
    s_score DOUBLE PRECISION NOT NULL DEFAULT 0,
    e_score DOUBLE PRECISION NOT NULL DEFAULT 0,
    c_score DOUBLE PRECISION NOT NULL DEFAULT 0,
    holland_code TEXT NOT NULL,
    dominant_traits_json TEXT,
    items_answered INTEGER NOT NULL DEFAULT 0,
    items_expected INTEGER NOT NULL DEFAULT 0,
    complete INTEGER NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    FOREIGN KEY (assessment_id) REFERENCES assessments(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS grit_scores (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    assessment_id INTEGER NOT NULL UNIQUE,
    persistence DOUBLE PRECISION NOT NULL DEFAULT 0,
    focus DOUBLE PRECISION NOT NULL DEFAULT 0,
    conscientiousness DOUBLE PRECISION NOT NULL DEFAULT 0,
    curiosity DOUBLE PRECISION NOT NULL DEFAULT 0,
    stress_resilience DOUBLE PRECISION NOT NULL DEFAULT 0,
    deliberate_practice DOUBLE PRECISION NOT NULL DEFAULT 0,
    response_to_failure DOUBLE PRECISION NOT NULL DEFAULT 0,
    composite_score DOUBLE PRECISION NOT NULL DEFAULT 0,
    normalized_index DOUBLE PRECISION NOT NULL DEFAULT 0,
    items_answered INTEGER NOT NULL DEFAULT 0,
    items_expected INTEGER NOT NULL DEFAULT 0,
    complete INTEGER NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    FOREIGN KEY (assessment_id) REFERENCES assessments(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS stream_scores (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    assessment_id INTEGER NOT NULL,
    stream_id TEXT NOT NULL,
    stream_name TEXT NOT NULL,
    fit_score DOUBLE PRECISION NOT NULL,
    fit_band TEXT NOT NULL,
    rank_order INTEGER NOT NULL,
    rationale_json TEXT,
    created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    FOREIGN KEY (assessment_id) REFERENCES assessments(id) ON DELETE CASCADE,
    UNIQUE(assessment_id, stream_id)
);

CREATE INDEX IF NOT EXISTS idx_stream_scores_rank ON stream_scores(assessment_id, rank_order);

-- Versioned stream weights / career clusters / curriculum mapping.
CREATE TABLE IF NOT EXISTS scoring_rules (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    version_id INTEGER NOT NULL,
    stream_id TEXT NOT NULL,
    stream_name TEXT NOT NULL,
    weight_config_json TEXT NOT NULL,
    is_active INTEGER NOT NULL DEFAULT 1,
    created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    updated_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    FOREIGN KEY (version_id) REFERENCES assessment_versions(id),
    UNIQUE(version_id, stream_id)
);

-- =========================================================
-- 4. PARENT INVENTORY (materialized deterministic summaries)
-- =========================================================
CREATE TABLE IF NOT EXISTS parent_expectations (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    assessment_id INTEGER NOT NULL,
    parent_id INTEGER NOT NULL,
    expected_stream TEXT NOT NULL,
    secondary_stream TEXT,
    outcome_priority TEXT NOT NULL,
    comments TEXT,
    created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    updated_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    FOREIGN KEY (assessment_id) REFERENCES assessments(id) ON DELETE CASCADE,
    FOREIGN KEY (parent_id) REFERENCES parents(id) ON DELETE CASCADE,
    UNIQUE(assessment_id, parent_id)
);

CREATE TABLE IF NOT EXISTS parent_perceptions (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    assessment_id INTEGER NOT NULL,
    parent_id INTEGER NOT NULL,
    observed_analytical DOUBLE PRECISION NOT NULL,
    observed_creative DOUBLE PRECISION NOT NULL,
    observed_study_habits DOUBLE PRECISION NOT NULL,
    observed_stress_resilience DOUBLE PRECISION NOT NULL,
    created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    updated_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    FOREIGN KEY (assessment_id) REFERENCES assessments(id) ON DELETE CASCADE,
    FOREIGN KEY (parent_id) REFERENCES parents(id) ON DELETE CASCADE,
    UNIQUE(assessment_id, parent_id)
);

CREATE TABLE IF NOT EXISTS congruence_scores (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    assessment_id INTEGER NOT NULL UNIQUE,
    parent_id INTEGER NOT NULL,
    congruence_pct DOUBLE PRECISION NOT NULL,
    alignment_status TEXT NOT NULL,
    stream_match_score DOUBLE PRECISION NOT NULL,
    perception_gap_score DOUBLE PRECISION NOT NULL,
    friction_factors_json TEXT,
    created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    updated_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    FOREIGN KEY (assessment_id) REFERENCES assessments(id) ON DELETE CASCADE,
    FOREIGN KEY (parent_id) REFERENCES parents(id)
);

-- =========================================================
-- 5. LLM & PROMPTS (audit trail is mandatory, not optional)
-- =========================================================
CREATE TABLE IF NOT EXISTS prompt_versions (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    prompt_type TEXT NOT NULL CHECK (prompt_type IN ('candidate_report', 'parent_report', 'counselor_report')),
    version_code TEXT NOT NULL UNIQUE,
    system_prompt TEXT NOT NULL,
    user_template TEXT NOT NULL,
    is_active INTEGER NOT NULL DEFAULT 1,
    created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    updated_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE IF NOT EXISTS llm_requests (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    assessment_id INTEGER,
    user_id INTEGER,
    report_type TEXT NOT NULL,
    prompt_version_id INTEGER,
    provider TEXT NOT NULL,
    model_name TEXT NOT NULL,
    request_payload_json TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'success', 'failed', 'fallback')),
    created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    FOREIGN KEY (assessment_id) REFERENCES assessments(id) ON DELETE SET NULL,
    FOREIGN KEY (prompt_version_id) REFERENCES prompt_versions(id)
);
CREATE INDEX IF NOT EXISTS idx_llm_requests_assessment ON llm_requests(assessment_id);
CREATE INDEX IF NOT EXISTS idx_llm_requests_created ON llm_requests(created_at);

CREATE TABLE IF NOT EXISTS llm_responses (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    request_id INTEGER NOT NULL,
    raw_response TEXT,
    token_usage_json TEXT,
    latency_ms INTEGER NOT NULL DEFAULT 0,
    status TEXT NOT NULL DEFAULT 'success' CHECK (status IN ('success', 'failed', 'fallback')),
    error_message TEXT,
    created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    FOREIGN KEY (request_id) REFERENCES llm_requests(id) ON DELETE CASCADE
);

-- =========================================================
-- 6. REPORTS (reproducible & versioned)
-- =========================================================
CREATE TABLE IF NOT EXISTS reports (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    assessment_id INTEGER NOT NULL,
    report_type TEXT NOT NULL CHECK (report_type IN ('candidate', 'parent', 'counselor')),
    title TEXT NOT NULL,
    structured_data_json TEXT NOT NULL,
    structured_input_hash TEXT NOT NULL,
    narrative_html TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'ready' CHECK (status IN ('pending', 'ready', 'failed')),
    prompt_version_id INTEGER,
    model TEXT,
    generated_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    updated_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    FOREIGN KEY (assessment_id) REFERENCES assessments(id) ON DELETE CASCADE,
    FOREIGN KEY (prompt_version_id) REFERENCES prompt_versions(id),
    UNIQUE(assessment_id, report_type)
);

CREATE TABLE IF NOT EXISTS report_versions (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    report_id INTEGER NOT NULL,
    version_number INTEGER NOT NULL,
    narrative_json TEXT NOT NULL,
    structured_input_hash TEXT,
    prompt_version_id INTEGER,
    model TEXT,
    generated_by TEXT NOT NULL DEFAULT 'system',
    created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    FOREIGN KEY (report_id) REFERENCES reports(id) ON DELETE CASCADE,
    UNIQUE(report_id, version_number)
);

-- =========================================================
-- 7. GOVERNANCE
-- =========================================================
CREATE TABLE IF NOT EXISTS audit_logs (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    user_id INTEGER,
    action TEXT NOT NULL,
    resource_type TEXT NOT NULL,
    resource_id TEXT,
    ip_address TEXT,
    details_json TEXT,
    created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_audit_logs_user ON audit_logs(user_id);
CREATE INDEX IF NOT EXISTS idx_audit_logs_created ON audit_logs(created_at);

-- Global configuration store: difficulty weights, fit bands, congruence config, thresholds.
-- Values are versioned-by-convention (bump the key's JSON payload and record an audit event).
CREATE TABLE IF NOT EXISTS admin_settings (
    key TEXT PRIMARY KEY,
    value_json TEXT NOT NULL,
    description TEXT,
    updated_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);
